set_project("tile-npu-sim")
set_languages("c++20")
set_warnings("all", "error")
-- Disable implicit FP contraction so that `a * b + c` keeps separate mul/add roundings
-- Explicit std::fma still emits a single-rounding FMA.
add_cxflags("-ffp-contract=off", { tools = { "gcc", "gxx", "clang", "clangxx" } })
set_config("ccachedir", path.join(os.projectdir(), ".cache", "ccache"))
add_rules("mode.debug", "mode.release")
add_moduledirs("xmake/modules")

option("native", function()
	set_default(false)
	set_showmenu(true)
	set_category("Build")
	set_description("Build with -march=native for host-specific ISA extensions")
end)

if has_config("native") then
	add_cxflags("-march=native", { tools = { "gcc", "gxx", "clang", "clangxx" } })
end

option("trace", function()
	set_default("none")
	set_values("none", "itrace", "mtrace", "all")
	set_showmenu(true)
	set_category("Debug")
	set_description("Trace features: none, itrace, mtrace, or all")
end)

option("trace_flush_records", function()
	set_default("4096")
	set_showmenu(true)
	set_category("Debug")
	set_description("Batch trace flush interval in records")
end)

local trace_mode = get_config("trace") or "none"
local trace_flush_records = tonumber(get_config("trace_flush_records") or "4096") or 0

-- Internal static library shared by the runner and the host test binaries.
target("sim_core", function()
	set_kind("static")
	set_default(false)
	add_files("src/*.cpp|main.cpp", "src/decode/*.cpp|disasm.cpp", "src/execute/*.cpp", "src/platform/*.cpp")
	if trace_mode ~= "none" then
		add_defines("CONFIG_TRACE", { public = true })
		add_defines("TRACE_FLUSH_RECORDS=" .. trace_flush_records, { public = true })
	end
	if trace_mode == "itrace" or trace_mode == "all" then
		add_defines("CONFIG_ITRACE", { public = true })
	end
	if trace_mode == "mtrace" or trace_mode == "all" then
		add_defines("CONFIG_MTRACE", { public = true })
		add_files("src/trace/mtrace/mtrace.cpp", "src/trace/mtrace/mtrace_writer.cpp")
	end
	add_includedirs("include", { public = true })
	add_includedirs("src")
end)

add_requires("cli11 2.7.2")

-- The default target is the runnable simulator.
target("sim", function()
	set_kind("binary")
	set_default(true)
	add_deps("sim_core")
	add_files("src/main.cpp", "src/monitor/monitor.cpp")
	add_includedirs("src")
	add_packages("cli11")
	if has_config("sdb") then
		add_files("src/monitor/sdb.cpp")
		add_defines("CONFIG_SDB")
	end
	if trace_mode == "itrace" or trace_mode == "all" then
		add_files("src/trace/itrace/disasm.cpp", "src/trace/itrace/itrace_writer.cpp")
	end
end)

option("sdb", function()
	set_default(false)
	set_showmenu(true)
	set_category("Debug")
	set_description("Enable the interactive sdb debugger in sim")
end)

target("sim_tests", function()
	set_kind("binary")
	set_default(false)
	add_deps("sim_core")
	add_files("tests/units/*.cpp")
	add_includedirs("src", "tests/include")
	add_tests("core")
end)

target("sim_guest_tests", function()
	set_kind("binary")
	set_default(false)
	add_deps("sim_core")
	add_files("tests/guest/main.cpp", "tests/guest/npu_guest_test.cpp")
	add_includedirs("src", "tests/include")
end)

option("riscv_cross", function()
	set_default("riscv64-linux-gnu-")
	set_showmenu(true)
	set_category("Guests")
	set_description("Prefix of the RISC-V toolchain used to assemble guest test images")
end)

option("qwen3_max_new_tokens", function()
	set_default("32")
	set_showmenu(true)
	set_category("Guests")
	set_description("Number of decode tokens generated by the Qwen3 app (0 = prefill only)")
end)

